number: int = 10
print( type(number) )

decimal: float = 2.5
print( type(decimal) )

text: str = "Hello, world!"
print( type(str) )

str2 = "" # str - blank
print( type(str2) )

str3 = " " # str - Empty Space
print( type(str3) )

active: bool = True
print( type(active) )

names: list = [ 'Vincent', 'Sarah', 'Marry' ]
print( type(names) )

coordinates: tuple = (1.5, 2.5)
print( type(coordinates) )

unique: set = {1, 4, 9}
print( type(unique) )

data: dict = {'name': 'Bob', 'age': 20}
print( type(data) )

none = None # None type
print( type(none))