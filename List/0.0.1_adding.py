# Using append
names = ["John", "Alice", "Sarah", "George"]
names.append("Demoner")

print(names)

# Using the + operator
names = names + ["Hacker"]

print(names)

# Using the extend method
# example about extend
example_list = ['Where the winds meet', 'Dota2']
names.extend(example_list)

print(names)

# Using the insert method
numbers = [1, 2, 4, 5]
numbers.insert(2, 3) #index, value

print(numbers)